// Scenario03 (假檢警) English + Japanese localization strings + language
// switch.
//
// getScenario03Lang() is the ONE place every scenario03 file should ask
// "which language is the player using". It reuses the existing app-wide
// language selector (src/lib/lang.js) - no new storage, no new route. It is
// a three-way check: 'en' -> 'en', 'jp' -> 'jp', anything else -> 'zh' so
// the Chinese run is always the safe default.
//
// zhTW strings below are copied verbatim from the components as they stood
// before this file existed, so switching a component over to `t.xxx` must
// never change what a Chinese-language player sees. The internal locale
// code for Japanese is always 'jp' - never 'ja' - anywhere in this file.
import { getLanguage } from '../../lib/lang';

export function getScenario03Lang() {
  const lang = getLanguage();
  if (lang === 'en') return 'en';
  if (lang === 'jp') return 'jp';
  return 'zh';
}

export function useScenario03Lang() {
  return getScenario03Lang();
}

